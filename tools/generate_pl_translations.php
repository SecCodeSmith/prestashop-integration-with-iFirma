/*
 * Generates translations/pl.php.
 *
 * Usage: php tools/generate_pl_translations.php
 *
 * Reads tools/pl_translations_map.php (English => Polish), scans the module for translatable
 * strings and writes the PrestaShop translation file. Exits with status 1 and lists the
 * strings that still lack a Polish translation.
 *
 * Scanned: ifirma.php, classes/*.php and controllers/ (->l('...' with an optional second argument
 * naming the translation file, otherwise the lowercase class name of the file; 'ifirma' for ifirma.php)
 * and views/templates/ ({l s='...' mod='ifirma'}, key = template basename).
 *
 * The PrestaShop key is md5() of the string with every ' written as \' (what Module::l() and
 * smartyTranslate() hash).
 */

$root = str_replace('\\', '/', dirname(__DIR__)) . '/';
$map = include __DIR__ . '/pl_translations_map.php';

/**
 * @param string $dir
 * @param string $ext
 * @return string[] paths relative to the module root, sorted
 */
function ifirma_list_files($root, $dir, $ext)
{
    $out = array();
    if (!is_dir($root . $dir)) {
        return $out;
    }
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root . $dir, FilesystemIterator::SKIP_DOTS));
    foreach ($it as $file) {
        if ($file->isFile() && substr($file->getFilename(), -strlen($ext)) === $ext && $file->getFilename() !== 'index.php') {
            $out[] = ltrim(substr(str_replace('\\', '/', $file->getPathname()), strlen($root)), '/');
        }
    }
    sort($out);

    return $out;
}

/**
 * @param string $root
 * @return array list of array(file, key, string)
 */
function ifirma_scan($root)
{
    $b = chr(92);
    $q = "((?:[^'" . $b . $b . "]|" . $b . $b . ".)*)";
    $tplRe = '/\{l s=\'' . $q . '\'\s+mod=\'ifirma\'(?:\s+js=1)?\}/';
    $phpRe = '/->l\(\s*\'' . $q . '\'(?:\s*,\s*\'([A-Za-z0-9_]+)\')?/';

    $files = array('ifirma.php' => 'ifirma');
    foreach (ifirma_list_files($root, 'classes', '.php') as $f) {
        $files[$f] = null;
    }
    foreach (ifirma_list_files($root, 'controllers', '.php') as $f) {
        $files[$f] = null;
    }
    foreach (ifirma_list_files($root, 'views/templates', '.tpl') as $f) {
        $files[$f] = null;
    }

    $found = array();
    foreach ($files as $file => $fixedKey) {
        $content = file_get_contents($root . $file);
        if (substr($file, -4) === '.tpl') {
            preg_match_all($tplRe, $content, $m);
            $key = basename($file, '.tpl');
            foreach (array_unique($m[1]) as $raw) {
                $found[] = array($file, $key, stripslashes($raw));
            }
            continue;
        }
        preg_match_all($phpRe, $content, $m, PREG_SET_ORDER);
        $seen = array();
        foreach ($m as $hit) {
            $key = $fixedKey !== null ? $fixedKey : (isset($hit[2]) && $hit[2] !== '' ? $hit[2] : strtolower(basename($file, '.php')));
            $string = stripslashes($hit[1]);
            if (isset($seen[$key . "\0" . $string])) {
                continue;
            }
            $seen[$key . "\0" . $string] = true;
            $found[] = array($file, $key, $string);
        }
    }

    return $found;
}

/**
 * @param string $key
 * @param string $string
 * @return string
 */
function ifirma_translation_key($key, $string)
{
    return '<{ifirma}prestashop>' . $key . '_' . md5(str_replace("'", "\\'", $string));
}

$lines = array();
$missing = array();
foreach (ifirma_scan($root) as $hit) {
    list($file, $key, $string) = $hit;
    if (!isset($map[$string])) {
        $missing[$string] = $file;
        continue;
    }
    $k = ifirma_translation_key($key, $string);
    $lines[$k] = "\$_MODULE['" . $k . "'] = '" . str_replace(array('\\', "'"), array('\\\\', "\\'"), $map[$string]) . "';";
}

if ($missing) {
    fwrite(STDERR, "MISSING " . count($missing) . " translation(s):\n");
    foreach ($missing as $string => $file) {
        fwrite(STDERR, $file . ' | ' . $string . "\n");
    }
    exit(1);
}

